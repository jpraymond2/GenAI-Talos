"""Does Recall sort the synthetic world into the right people? (no LLM, ~10 s)

    uv run python scripts/synthetic/check_identity.py [--root data/synthetic] [--keep]

Builds a throwaway World Model from data/synthetic/tables (never touches
data/world_sample.db), then compares every person entity it made against
ground_truth/people.json and prints a scorecard:

  - perfect people: exactly one entity, holding nobody else
  - split people: one real person spread over several entities
  - wrong merges: one entity holding several real people
  - not-people: newsletters / receipts / the owner turned into "contacts"
  - junk attributes: org/city values that aren't true for that person
  - hard cases: the specific traps built into the dataset

Writes the full result to logs/eval/identity_<timestamp>.json.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sqlite3
import sys
import tempfile
from collections import defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))


def build_world(tables: Path, work: Path) -> Path:
    """Ingest the synthetic tables into a temp world DB using the real pipeline."""
    os.environ.update(SAMPLE_MODE="true", NVIDIA_API_KEY="", DATA_BACKEND="duckdb",
                      SAMPLE_DATA_DIR=str(tables.resolve()), LOGS_DIR=str((work / "logs").resolve()))
    from recall.config import get_settings
    from recall.data.duckdb_backend import DuckDBBackend
    from recall.data.query_layer import get_query_layer
    from recall.engines.world.ingest import IngestPipelineService
    from recall.engines.world.store import WorldStore
    from recall.llm.generator import reset_client
    from recall.tracing import Tracer

    get_settings.cache_clear()
    reset_client()
    DuckDBBackend.clear_connection_cache()
    settings = get_settings()
    object.__setattr__(settings, "sample_data_dir", tables.resolve())
    object.__setattr__(settings, "sample_mode", True)
    object.__setattr__(settings, "logs_dir", (work / "logs").resolve())
    db = work / "world_synthetic.db"
    tracer = Tracer(logs_dir=work / "logs")
    with tracer.activate():
        store = WorldStore(path=db, settings=settings)
        counts = IngestPipelineService(store=store, settings=settings, tracer=tracer).run(get_query_layer(settings, tracer=tracer))
        store.close()
    print(f"ingest: {counts}")
    return db


def _md(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def write_report(path: Path, *, people, holders, entity_info, entity_people, perfect, split, unknown, merges, cases, junk,
                 merge_rows, services, n_entities) -> None:
    """Markdown scorecard that GitHub renders: how Recall sorted the synthetic world into people."""
    real = [p for p in people if p != "owner"]
    knowable = len(real) - len(unknown)
    lines = [
        "# How Recall sorted the synthetic contacts",
        "",
        f"_Generated by `scripts/synthetic/check_identity.py` on {datetime.now():%Y-%m-%d %H:%M}. "
        "Built from `data/synthetic/tables` with the real World Model ingest (no LLM)._",
        "",
        "| | |", "|---|---|",
        f"| Real people in the answer key | {len(real)} |",
        f"| Contacts Recall created | {n_entities} |",
        f"| **Sorted perfectly** (one contact, nobody else) | **{len(perfect)} / {knowable} ({100 * len(perfect) / max(1, knowable):.0f}%)** |",
        f"| Split into several contacts | {len(split)} |",
        f"| Split but impossible to know (unsaved number, never says who it is) | {len(unknown)} |",
        f"| **Wrongly merged** (two people in one contact) | **{len(merges)}** |",
        f"| Newsletters / no-reply senders moved out of people | {len(services)} |",
        f"| Contacts with a nonsense company (from chat text) | {len(junk)} |",
        "",
        "## Hard cases",
        "",
        "| | Check |", "|---|---|",
    ]
    lines += [f"| {'✅' if ok else '❌'} | {_md(name)} |" for name, ok in cases.items()]
    lines += ["", "## Every person and the contact(s) Recall made", "",
              "| Person (truth) | Result | Contact(s) Recall made — name · messages |", "|---|---|---|"]
    order = sorted(real, key=lambda p: (p in perfect, people[p]["name"]))
    for pid in order:
        status = "✅ one contact" if pid in perfect else "⚪ unknowable split" if pid in unknown else "⚠️ split" if pid in split else "❌ check"
        cells = []
        for eid in holders.get(pid, []):
            info = entity_info[eid]
            shared = [people[o]["name"] for o in entity_people[eid] if o not in (pid,)]
            cells.append(f"**{_md(info['name'])}** · {info['mentions']} msgs" + (f" · also holds {', '.join(shared)}" if shared else ""))
        lines.append(f"| {_md(people[pid]['name'])} ({people[pid]['relationship']}) | {status} | {'<br>'.join(cells) or '—'} |")
    lines += ["", "## Merge decisions (same or similar names)", "",
              "Score ≥ 0.75 merges, 0.55–0.75 asks the user (an LLM may settle it first in live mode), lower keeps apart. "
              "If another contact fits about as well, Recall asks instead of guessing. Identical phone/email always merges. "
              "**Confidence** = how likely the pair is one person, from the score.", "",
              "| Decision | Same person? | Score | Contact A | Contact B | Why | Why not |", "|---|---|---|---|---|---|---|"]
    icon = {"merged": "🔗 merged", "ask": "❓ ask user", "kept_apart": "↔️ kept apart"}
    for r in merge_rows:
        if r["decision"] == "kept_apart" and r["score"] < 0.3:
            continue
        conf = r.get("confidence", 1.0)
        verdict = icon.get(r["decision"], r["decision"])
        shown = conf
        lines.append(f"| {verdict} | {shown:.0%} | {r['score']:.2f} | {_md(r['name_a'])} | {_md(r['name_b'])} | "
                     f"{_md('; '.join(json.loads(r['reasons_for'])))} | {_md('; '.join(json.loads(r['reasons_against'])))} |")
    if services:
        lines += ["", "## Moved out of people (not a person)", "", ", ".join(_md(x) for x in services)]
    if junk:
        lines += ["", "## Contacts with a company that isn't real", "",
                  "These come from chat text being read as an employer (World Model org extraction).", "",
                  "| Contact | Stored company | True company |", "|---|---|---|"]
        lines += [f"| {_md(j['entity'])} | {_md(j['value'])} | {_md(j['true'] or '—')} |" for j in junk]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="")


def norm(s: str) -> str:
    return " ".join(s.lower().split())


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default="data/synthetic")
    ap.add_argument("--keep", action="store_true", help="keep the temp world DB and print its path")
    ap.add_argument("--report", default="data/synthetic/identity_report.md", help="Markdown report (renders on GitHub)")
    args = ap.parse_args()
    root = Path(args.root)
    people = json.loads((root / "ground_truth" / "people.json").read_text(encoding="utf-8"))

    # ---------- truth lookups
    handle_owner: dict[str, str] = {}
    label_owner: dict[str, set[str]] = defaultdict(set)
    msgr_owner: dict[str, str] = {}
    for pid, p in people.items():
        for h in p["handles"]:
            handle_owner[norm(h["value"])] = pid
        for label in p["display_labels"] + [p["name"], (p.get("contact_card") or {}).get("fn") or ""]:
            if label:
                label_owner[norm(label)].add(pid)
    # Messenger display names are unique per person in this dataset
    for pid, p in people.items():
        for label in p["display_labels"]:
            if len(label_owner[norm(label)]) == 1:
                msgr_owner[norm(label)] = pid
    msgr_owner[norm("Daniel Kim")] = "daniel_cl"  # the investor isn't on Messenger
    owner_handles = {norm(h["value"]) for h in people["owner"]["handles"]} | {norm("+15145550199")}

    work = Path(tempfile.mkdtemp(prefix="recall-identity-"))
    try:
        db = build_world(root / "tables", work)
        con = sqlite3.connect(db)
        con.row_factory = sqlite3.Row
        ents = con.execute("SELECT id, canonical_name, aliases_json, attributes_json, mention_count FROM entities WHERE type='person'").fetchall()
        obs_refs: dict[str, set[str]] = defaultdict(set)
        for r in con.execute("SELECT entity_id, source_ref FROM observations"):
            obs_refs[r["entity_id"]].add(r["source_ref"].split(":", 1)[0])
        links: dict[str, set[str]] = defaultdict(set)
        for r in con.execute("SELECT entity_id, handle_value FROM handle_links WHERE status IN ('active','new')"):
            links[r["entity_id"]].add(norm(r["handle_value"]))

        # ---------- map each entity to the real people it contains
        entity_people: dict[str, set[str]] = {}
        entity_info: dict[str, dict] = {}
        not_people: list[str] = []
        for e in ents:
            aliases = [norm(a) for a in json.loads(e["aliases_json"])] + [norm(e["canonical_name"])]
            handles = {a for a in aliases if "@" in a or a.startswith("+")} | links[e["id"]]
            pids = {handle_owner[h] for h in handles if h in handle_owner}
            if handles & owner_handles:
                pids.add("owner")
            if not pids:  # name-only entity: resolve by name, Messenger names first
                name = norm(e["canonical_name"])
                if "messenger" in obs_refs[e["id"]] and name in msgr_owner:
                    pids = {msgr_owner[name]}
                elif name in label_owner:
                    pids = set(label_owner[name])
            attrs = json.loads(e["attributes_json"])
            entity_info[e["id"]] = {"name": e["canonical_name"], "mentions": e["mention_count"], "people": sorted(pids),
                                    "org": attrs.get("org", ""), "city": attrs.get("city", "")}
            if not pids:
                not_people.append(e["canonical_name"])
            entity_people[e["id"]] = pids

        holders: dict[str, list[str]] = defaultdict(list)
        for eid, pids in entity_people.items():
            for pid in pids:
                holders[pid].append(eid)

        merge_rows = [dict(r) for r in con.execute("SELECT * FROM merge_decisions ORDER BY score DESC")] if con.execute(
            "SELECT name FROM sqlite_master WHERE name='merge_decisions'").fetchone() else []
        services = [r[0] for r in con.execute(
            "SELECT canonical_name FROM entities WHERE type='org' AND aliases_json LIKE '%@%' ORDER BY canonical_name")]

        def unknowable(pid: str) -> bool:
            """A number the owner never saved and that never says who it is can't be tied to a name."""
            p = people[pid]
            if p.get("contact_card"):
                return False
            bare = [e for e in holders.get(pid, []) if entity_info[e]["name"].startswith("+")]
            return bool(bare) and len(holders.get(pid, [])) > 1

        real = [pid for pid in people if pid != "owner"]
        perfect, split, missing, unknown = [], [], [], []
        for pid in real:
            hs = holders.get(pid, [])
            if not hs:
                missing.append(pid)
            elif len(hs) == 1 and entity_people[hs[0]] == {pid}:
                perfect.append(pid)
            elif len(hs) > 1 and unknowable(pid):
                unknown.append(pid)
            elif len(hs) > 1:
                split.append(pid)
        merges = [eid for eid, pids in entity_people.items() if len(pids - {"owner"}) > 1 or ("owner" in pids and len(pids) > 1)]
        owner_entities = holders.get("owner", [])

        # ---------- junk attributes
        junk = []
        for eid, info in entity_info.items():
            if len(info["people"]) != 1 or info["people"][0] == "owner":
                continue
            truth = people[info["people"][0]]
            org = info["org"]
            if org and norm(org) not in {norm(truth["org"]), norm((truth.get("contact_card") or {}).get("org") or "")}:
                junk.append({"entity": info["name"], "field": "org", "value": org, "true": truth["org"]})

        # ---------- hard cases
        def one_entity(*pids: str) -> bool:
            sets = [set(holders.get(p, [])) for p in pids]
            return all(len(s) == 1 for s in sets) and len(set.union(*sets)) == len(pids) and all(len(entity_people[next(iter(s))]) == 1 for s in sets)

        def together(pid: str) -> bool:
            return len(holders.get(pid, [])) == 1

        def apart(a: str, b: str) -> bool:
            return not (set(holders.get(a, [])) & set(holders.get(b, [])))

        cases = {
            "Three Omars kept apart": apart("omar_h", "omar_b") and apart("omar_h", "omar_k") and apart("omar_b", "omar_k"),
            "Two Daniel Kims kept apart": apart("daniel_vc", "daniel_cl"),
            "Messenger 'Daniel Kim' matched to the UofT friend (by what they talk about), not the investor": together("daniel_cl"),
            "Sasha = Alexandra Petrova (one entity)": together("sasha"),
            "Priya's old + new email = one entity": together("priya"),
            "Yusuf's old + new number = one entity": together("yusuf"),
            "Lucas is one entity (contacts + iMessage + Messenger)": together("lucas"),
            "Maman = Nadia Lefebvre (one entity)": together("mom"),
            "Amira (first-name card) = Amira Khalil (email)": together("f_amira"),
            "Owner is a single 'self' entity": len(owner_entities) == 1,
            "Newsletters/receipts not stored as people": not not_people,
            "Tyler (assistant) and Rachel kept apart": apart("tyler", "rachel"),
        }

        # ---------- print
        n = len(real)
        print()
        print(f"People in the answer key: {n}   Person entities Recall made: {len(ents)}")
        knowable = n - len(unknown)
        print(f"  perfect (1 entity, nobody else):   {len(perfect):3d}  ({100 * len(perfect) / knowable:.0f}% of the {knowable} that can be known)")
        print(f"  split across several entities:     {len(split):3d}")
        print(f"  split, but impossible to know:     {len(unknown):3d}  (unsaved numbers that never say who they are)")
        print(f"  wrongly merged with someone else:  {len(merges):3d} entities")
        print(f"  never found:                       {len(missing):3d}")
        print(f"  owner ('Jordan') entities:         {len(owner_entities):3d}  (should be 1)")
        print(f"  non-people stored as people:       {len(not_people):3d}  e.g. {', '.join(sorted(set(not_people))[:5])}")
        print(f"  entities with a wrong 'org':       {len(junk):3d}  e.g. {', '.join(repr(j['value'][:30]) for j in junk[:3])}")
        print()
        print("Hard cases:")
        for name, ok in cases.items():
            print(f"  [{'PASS' if ok else 'FAIL'}] {name}")
        print()
        if split:
            print("Split people (one person, several entities):")
            for pid in split:
                print(f"  {people[pid]['name']:<22} -> " + " | ".join(f"{entity_info[e]['name']} ({entity_info[e]['mentions']})" for e in holders[pid]))
        if merges:
            print("Wrong merges:")
            for eid in merges:
                print(f"  {entity_info[eid]['name']:<22} holds " + ", ".join(people[p]["name"] for p in entity_info[eid]["people"]))

        write_report(Path(args.report), people=people, holders=holders, entity_info=entity_info, entity_people=entity_people,
                     perfect=perfect, split=split, unknown=unknown, merges=merges, cases=cases, junk=junk,
                     merge_rows=merge_rows, services=services, n_entities=len(ents))
        print(f"Report: {args.report}")

        out_dir = ROOT / "logs" / "eval"
        out_dir.mkdir(parents=True, exist_ok=True)
        out = out_dir / f"identity_{datetime.now():%Y%m%d_%H%M%S}.json"
        out.write_text(json.dumps({
            "people": n, "entities": len(ents), "perfect": perfect, "split": {p: [entity_info[e] for e in holders[p]] for p in split},
            "merges": [entity_info[e] for e in merges], "missing": missing, "not_people": sorted(set(not_people)),
            "junk_attributes": junk, "hard_cases": cases, "entities_detail": entity_info, "unknowable": unknown,
            "merge_decisions": merge_rows, "not_people_retyped": services,
        }, indent=2, ensure_ascii=False), encoding="utf-8", newline="")
        print(f"\nFull result: {out}")
        con.close()
    finally:
        if args.keep:
            print(f"World DB kept at {work}")
        else:
            shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
